// Keep original photos intact. Generate full-resolution WebP and card-sized variants.
import sharp from 'sharp';
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root='public/franchise',out=root+'/PhotosWeb';await fs.mkdir(out,{recursive:true});
const teams=JSON.parse(await fs.readFile(root+'/Data/teams.json','utf8'));
const manifest={};let originalBytes=0,fullBytes=0,cardBytes=0;
for(const team of teams){for(const [i,path]of team.photos.entries()){
 const input=await fs.readFile(root+'/'+path),name=path.split('/').pop().replace(/\.[^.]+$/,'');
 const full=await sharp(input).webp({quality:92,effort:5}).toBuffer();
 const card=await sharp(input).resize({width:960,height:960,fit:'inside',withoutEnlargement:true}).webp({quality:90,effort:5}).toBuffer();
 const entry={next:team.photos[(i+1)%team.photos.length]};
 for(const [variant,buffer]of [['full',full],['card',card]]){
  const hash=createHash('sha256').update(buffer).digest('hex').slice(0,12);
  const file=`${name}-${variant}.${hash}.webp`;await fs.writeFile(out+'/'+file,buffer);entry[variant]='/franchise/PhotosWeb/'+file;
 }
 manifest[path]=entry;originalBytes+=input.length;fullBytes+=full.length;cardBytes+=card.length;
}}
await fs.writeFile(root+'/photo-assets.js','// Generated by scripts/optimize-franchise-photos.mjs.\nexport const photos='+JSON.stringify(manifest,null,2)+';\n');
console.log(JSON.stringify({photos:Object.keys(manifest).length,originalBytes,fullBytes,cardBytes},null,2));
